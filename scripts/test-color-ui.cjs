const { _electron: electron } = require(process.env.PLAYWRIGHT_PATH || 'playwright')
const { resolve } = require('node:path')
const assert = require('node:assert/strict')

;(async () => {
  const env = { ...process.env }
  delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath: require('electron'), args: [resolve('scripts/electron-test-entry.cjs')], env, timeout: 30000 })
  try {
    const page = await app.firstWindow()
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.getByRole('button', { name: 'Color Lab', exact: true }).click()
    await page.getByRole('heading', { name: 'Cor em foco' }).waitFor()
    await page.waitForFunction(() => !document.querySelector('[aria-busy=true]'))
    await page.getByRole('textbox', { name: 'Cor HEX', exact: true }).fill('#9D7BFF')
    await page.getByRole('button', { name: 'Aplicar HEX' }).click()
    assert.ok(await page.getByText('3.13:1', { exact: true }).isVisible())
    await page.getByRole('button', { name: 'Copiar', exact: true }).first().click()
    assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), '#9D7BFF')
    await page.getByRole('button', { name: '+ Guardar no historico', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Cor guardada' }).waitFor()
    await page.screenshot({ path: 'release/color-lab-preview.png', fullPage: true })
    await page.getByRole('button', { name: 'Criar paleta com esta harmonia' }).click()
    await page.getByRole('textbox', { name: 'Nome da paleta', exact: true }).fill('Smoke Color Lab')
    await page.getByRole('button', { name: 'Salvar paleta', exact: true }).click()
    await page.getByRole('status').filter({ hasText: 'Paleta salva' }).waitFor()
    const palette = page.locator('.color-palette').filter({ has: page.getByRole('heading', { name: 'Smoke Color Lab', exact: true }) })
    assert.equal(await palette.locator('.color-palette-strip button').count(), 5)
    await palette.getByRole('button', { name: 'Renomear', exact: true }).click()
    await page.getByRole('textbox', { name: 'Novo nome', exact: true }).fill('Smoke Renamed')
    await page.getByRole('button', { name: 'Salvar nome' }).click()
    await page.getByRole('heading', { name: 'Smoke Renamed', exact: true }).waitFor()
    await page.reload()
    await page.getByRole('button', { name: 'Minhas Paletas', exact: true }).click()
    await page.getByRole('heading', { name: 'Smoke Renamed', exact: true }).waitFor()
    await page.screenshot({ path: 'release/palettes-preview.png', fullPage: true })
    const renamed = page.locator('.color-palette').filter({ has: page.getByRole('heading', { name: 'Smoke Renamed', exact: true }) })
    await renamed.getByRole('button', { name: 'Excluir', exact: true }).click()
    await renamed.getByRole('button', { name: 'Confirmar exclusao' }).click()
    await page.getByRole('status').filter({ hasText: 'Paleta excluida' }).waitFor()
    assert.equal(await app.evaluate(({ globalShortcut }) => globalShortcut.isRegistered('Ctrl+Alt+Shift+F9')), true)
    await page.locator('.workspace-live').click()
    await page.waitForTimeout(800)
    const processInfo = require('node:child_process').execFileSync('powershell.exe', ['-NoProfile', '-Command', "Get-Process -Name 'GCPShot.LiveColor' | Select-Object ProcessName,MainWindowTitle | ConvertTo-Json"], { encoding: 'utf8' })
    assert.ok(processInfo.includes('GCPShot.LiveColor'), 'Live Color panel must be running')
    require('node:child_process').execFileSync('powershell.exe', ['-NoProfile', '-Command', "Add-Type -AssemblyName System.Windows.Forms; [System.Windows.Forms.SendKeys]::SendWait('{ESC}')"])
    await page.waitForFunction(() => document.querySelector('[role=status]').textContent.includes('cancelada'))
    assert.equal(await page.isVisible('body'), true)
    assert.equal(app.windows().length, 1, 'Cancel should leave only the main window')
    const swatch = await app.evaluate(async ({ BrowserWindow, screen }) => {
      const area = screen.getPrimaryDisplay().workArea
      const sample = new BrowserWindow({ x: area.x + 40, y: area.y + 40, width: 250, height: 250, frame: false, backgroundColor: '#12A4B6', alwaysOnTop: true, webPreferences: { sandbox: true } })
      await sample.loadURL('data:text/html,<body style="margin:0;background:%2312A4B6"></body>')
      return { id: sample.id, x: area.x + 140, y: area.y + 140 }
    })
    await page.locator('.workspace-live').click()
    await page.waitForTimeout(800)
    require('node:child_process').execFileSync('powershell.exe', ['-NoProfile', '-Command', `Add-Type -TypeDefinition 'using System; using System.Runtime.InteropServices; public class ColorTestMouse { [DllImport("user32.dll")] public static extern bool SetCursorPos(int x, int y); [DllImport("user32.dll")] public static extern void mouse_event(uint f, uint x, uint y, uint d, UIntPtr e); }'; [ColorTestMouse]::SetCursorPos(${swatch.x}, ${swatch.y}) | Out-Null; Start-Sleep -Milliseconds 300; [ColorTestMouse]::mouse_event(2,0,0,0,[UIntPtr]::Zero); [ColorTestMouse]::mouse_event(4,0,0,0,[UIntPtr]::Zero)`])
    await page.getByRole('status').filter({ hasText: '#12A4B6 copiado' }).waitFor()
    assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), '#12A4B6')
    assert.equal((await page.evaluate(() => window.gcpshot.getColorLibrary())).history[0], '#12A4B6')
    await app.evaluate(({ BrowserWindow }, id) => BrowserWindow.fromId(id).destroy(), swatch.id)
    let toast
    for (let attempt = 0; attempt < 40; attempt++) {
      toast = app.windows().find((w) => w.url().includes('color-toast.html'))
      if (toast) break
      await page.waitForTimeout(50)
    }
    assert.ok(toast, 'A branded GCPShot notification should be visible')
    await toast.getByRole('button', { name: 'Abrir Color Lab', exact: true }).waitFor()
    assert.ok((await toast.locator('header').textContent()).includes('GCPShot'))
    await toast.screenshot({ path: 'release/live-color-toast-preview.png' })
    await (await app.browserWindow(page)).evaluate((window) => window.hide())
    await toast.getByRole('button', { name: 'Abrir Color Lab', exact: true }).click()
    await page.getByRole('heading', { name: 'Color Lab', exact: true }).waitFor()
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().some((w) => w.isVisible() && w.webContents.getURL().includes('/renderer/'))), true)
    assert.equal(await page.getByRole('textbox', { name: 'Cor HEX', exact: true }).inputValue(), '#12A4B6')
    const transfer = resolve('release/test-profile/exported-palettes.json')
    await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, transfer)
    assert.equal(await page.evaluate(() => window.gcpshot.exportColorLibrary('json')), true)
    const exported = JSON.parse(require('node:fs').readFileSync(transfer, 'utf8'))
    assert.ok(Array.isArray(exported.palettes))
    await app.evaluate(({ dialog }, target) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [target] }) }, transfer)
    const imported = await page.evaluate(() => window.gcpshot.importColorLibrary())
    assert.equal(imported.palettes.length, exported.palettes.length * 2)
    const cssFile = resolve('release/test-profile/exported-palettes.css')
    await app.evaluate(({ dialog }, target) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: target }) }, cssFile)
    assert.equal(await page.evaluate(() => window.gcpshot.exportColorLibrary('css')), true)
    assert.ok(require('node:fs').readFileSync(cssFile, 'utf8').startsWith(':root {'))
    await page.evaluate(() => window.gcpshot.beginCapture('region'))
    await page.waitForTimeout(400)
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((w) => !w.webContents.getURL().includes('capture=1')).isVisible()), false)
    await page.evaluate(() => window.gcpshot.cancelCapture())
    assert.equal(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].isVisible()), false, 'Capture cancel must not reopen the main page')
    assert.deepEqual(errors, [])
    console.log('Floating Live Color, real pixel sampling, clipboard/history, branded notification click-to-Color-Lab, palettes and capture regression passed.')
  } finally { await app.evaluate(({ app }) => app.quit()).catch(() => {}); await app.close().catch(() => {}) }
})().catch((e) => { console.error(e); process.exitCode = 1 })
