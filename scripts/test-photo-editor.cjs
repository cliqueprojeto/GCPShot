const assert = require('node:assert/strict')
const sharp = require('sharp')
const { join } = require('node:path')
const { readFileSync } = require('node:fs')

module.exports = async function testPhotoEditor(app, page) {
  const navigation = page.getByRole('navigation', { name: 'Navegação principal' })
  await page.locator('.workspace-sidebar').getByRole('button', { name: 'Configurações', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  await page.getByRole('dialog').getByRole('tab').nth(2).click()
  await page.getByRole('dialog').locator('select').nth(1).selectOption('pt-BR')
  for (const name of ['Geral', 'Teclas de atalho', 'Formatos']) {
    await page.getByRole('tab', { name, exact: true }).click()
    const dialog = page.getByRole('dialog')
    assert.equal(await dialog.evaluate((node) => getComputedStyle(node.querySelector('.settings-window')).borderRadius), '8px')
    if (name === 'Teclas de atalho') await page.screenshot({ path: 'release/settings-shortcuts-0.6.0.png' })
  }
  await page.screenshot({ path: 'release/settings-0.6.0.png' })
  await page.getByRole('button', { name: 'Fechar configurações', exact: true }).click()
  const center = await sharp({ create: { width: 100, height: 80, channels: 4, background: '#5F42EB' } }).png().toBuffer()
  const png = await sharp({ create: { width: 320, height: 240, channels: 4, background: '#ffffff' } }).composite([{ input: center, left: 110, top: 80 }]).png().toBuffer()
  await navigation.getByRole('button', { name: 'Captura', exact: true }).click()
  await page.evaluate((dataUrl) => {
    const library = JSON.parse(localStorage.getItem('gcpshot-studio-library') || '[]')
    localStorage.setItem('gcpshot-studio-library', JSON.stringify([{ id: 'editor-fixture', name: 'Editor fixture', width: 320, height: 240, dataUrl, createdAt: Date.now() + 10000 }, ...library.filter((item) => !item.name.startsWith('Editor fixture'))]))
  }, 'data:image/png;base64,' + png.toString('base64'))
  await navigation.getByRole('button', { name: 'Estúdio', exact: true }).click()
  await page.locator('.studio-thumb[title="Editor fixture"]').click()
  const editor = page.getByRole('region', { name: 'Editor de imagem', exact: true })
  const image = editor.locator('.photo-image-frame img')
  await image.waitFor({ state: 'visible' })
  await page.waitForFunction(() => document.querySelector('.photo-status')?.textContent.includes('320 × 240'))
  const readPixels = async () => {
    await page.waitForTimeout(250)
    const url = await image.getAttribute('src')
    return sharp(Buffer.from(url.split(',')[1], 'base64')).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  }
  let pixels = await readPixels()
  assert.deepEqual([...pixels.data.subarray(0, 4)], [255, 255, 255, 255])
  await editor.getByRole('button', { name: 'Fundo', exact: true }).click()
  await editor.getByRole('button', { name: 'Remover fundo', exact: true }).click()
  await page.waitForFunction(() => !document.querySelector('.photo-status')?.textContent.includes('Aplicando'))
  pixels = await readPixels()
  assert.equal(pixels.data[3], 0)
  assert.equal(pixels.data[(120 * 320 + 160) * 4 + 3], 255)
  const exportedPath = join(await app.evaluate(({ app }) => app.getPath('userData')), 'photo-editor-test.png')
  await app.evaluate(({ dialog }, path) => {
    const original = dialog.showSaveDialog
    dialog.showSaveDialog = async () => { dialog.showSaveDialog = original; return { canceled: false, filePath: path } }
  }, exportedPath)
  await page.getByRole('button', { name: 'Exportar PNG', exact: true }).click()
  await page.waitForTimeout(400)
  const exportedPixels = await sharp(readFileSync(exportedPath)).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  assert.equal(exportedPixels.info.width, 320)
  assert.equal(exportedPixels.info.height, 240)
  assert.equal(exportedPixels.data[3], 0)
  await editor.getByRole('button', { name: 'Desfazer edição', exact: true }).click()
  pixels = await readPixels(); assert.equal(pixels.data[3], 255)
  await editor.getByRole('button', { name: 'Refazer edição', exact: true }).click()
  pixels = await readPixels(); assert.equal(pixels.data[3], 0)
  await editor.getByRole('button', { name: 'Restaurar original', exact: true }).click()
  await editor.getByRole('button', { name: 'Recorte', exact: true }).click()
  await editor.getByRole('button', { name: 'Girar à direita', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.photo-status')?.textContent.includes('240 × 320'))
  await editor.getByRole('button', { name: 'Espelhar verticalmente', exact: true }).click()
  await page.waitForTimeout(250)
  await image.scrollIntoViewIfNeeded()
  const bounds = await image.boundingBox()
  await page.mouse.move(bounds.x + bounds.width * .2, bounds.y + bounds.height * .2)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width * .8, bounds.y + bounds.height * .8, { steps: 5 })
  await page.mouse.up()
  await editor.getByRole('button', { name: 'Aplicar recorte', exact: true }).click()
  await page.waitForTimeout(300)
  pixels = await readPixels()
  assert.ok(pixels.info.width < 240 && pixels.info.height < 320)
  await editor.getByRole('button', { name: 'Desfazer edição', exact: true }).click()
  await editor.getByRole('button', { name: 'Luz e cor', exact: true }).click()
  await editor.getByRole('slider', { name: 'Exposição', exact: true }).fill('25')
  pixels = await readPixels()
  assert.ok(pixels.data[(160 * 240 + 120) * 4] > 95)
  await editor.getByRole('button', { name: 'Restaurar original', exact: true }).click()
  await editor.getByRole('button', { name: 'Marcação', exact: true }).click()
  await page.waitForTimeout(250)
  await image.scrollIntoViewIfNeeded()
  const brushBounds = await image.boundingBox()
  await page.mouse.move(brushBounds.x + 20, brushBounds.y + 20)
  await page.mouse.down()
  await page.mouse.move(brushBounds.x + 80, brushBounds.y + 20, { steps: 5 })
  await page.mouse.up()
  pixels = await readPixels()
  assert.deepEqual([...pixels.data.subarray((20 * 320 + 50) * 4, (20 * 320 + 50) * 4 + 3)], [95, 66, 235])
  await editor.getByRole('button', { name: 'Salvar cópia na biblioteca', exact: true }).click()
  await page.locator('.studio-thumb[title="Editor fixture (editado)"]').waitFor()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('gcpshot-studio-library')).find((item) => item.name === 'Editor fixture (editado)'))
  assert.equal(saved.width, 320); assert.equal(saved.height, 240)
  await page.waitForTimeout(300)
  await page.locator('.workspace-content').evaluate((node) => node.scrollTo(0, 0))
  await page.screenshot({ path: 'release/photo-editor-0.6.0.png' })
  const large = await sharp({ create: { width: 5000, height: 80, channels: 4, background: '#5F42EB' } }).png().toBuffer()
  await navigation.getByRole('button', { name: 'Captura', exact: true }).click()
  await page.evaluate((dataUrl) => {
    const library = JSON.parse(localStorage.getItem('gcpshot-studio-library') || '[]')
    localStorage.setItem('gcpshot-studio-library', JSON.stringify([{ id: 'editor-large', name: 'Editor large', width: 5000, height: 80, dataUrl, createdAt: Date.now() + 20000 }, ...library.filter((item) => !item.name.startsWith('Editor large'))]))
  }, 'data:image/png;base64,' + large.toString('base64'))
  await navigation.getByRole('button', { name: 'Estúdio', exact: true }).click()
  await page.locator('.studio-thumb[title="Editor large"]').click()
  await page.waitForFunction(() => document.querySelector('.photo-status')?.textContent.includes('5000 × 80'))
  await editor.getByRole('button', { name: 'Salvar cópia na biblioteca', exact: true }).click()
  await page.locator('.studio-thumb[title="Editor large (editado)"]').waitFor()
  const fullSize = await page.evaluate(() => JSON.parse(localStorage.getItem('gcpshot-studio-library')).find((item) => item.name === 'Editor large (editado)'))
  assert.equal(fullSize.width, 5000); assert.equal(fullSize.height, 80)
  assert.equal((await sharp(Buffer.from(fullSize.dataUrl.split(',')[1], 'base64')).metadata()).width, 5000)
  await page.locator('.studio-thumb[title="Editor fixture (editado)"]').click()
  console.log('Settings + editor: background alpha, undo/redo, rotate/flip, crop, exposure, brush and saved copy passed.')
}
